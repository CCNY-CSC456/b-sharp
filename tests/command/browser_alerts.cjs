  const airport={airport_id:'DEMO-001',latitude:40.6413,longitude:-73.7781,perimeter:21000,number_of_runways:10,assignment_source:'runway_assignments',observed_at:'2026-11-19T10:00:00Z',runways:Array.from({length:10},(_,i)=>({runway_id:i+1,status:'Available',timestamp:'2026-11-19T10:00:00',aircraft_id:null}))};
  const aircraft={aircraft:[{aircraft_id:'A1',latitude:40.70,longitude:-73.80,altitude:2000,status:'Landing',timestamp:'2026-11-19T10:00:00'},{aircraft_id:'B2',latitude:40.75,longitude:-73.82,altitude:2500,status:'Landing',timestamp:'2026-11-19T10:00:00'}],invalid_coordinate_count:0,departed_count:0,lifecycle_available:true};
  await page.route('http://command.test/**', async route=>{
    const url=new URL(route.request().url());
    if(url.pathname==='/') return route.fulfill({contentType:'text/html',body:html});
    if(url.pathname==='/api/alerts' && failed) return route.fulfill({status:503,body:'unavailable'});
    const body=({'/api/airport':airport,'/api/aircraft':aircraft,'/api/command-messages':[],'/api/alerts':state})[url.pathname] || {};
    return route.fulfill({contentType:'application/json',body:JSON.stringify(body)});
  });
  const refresh=async()=>{await page.waitForFunction(()=>!refreshing); await page.evaluate(()=>refreshDashboard());};
  const incident=(id,severity=1)=>({key:`${severity===1?'separation':'conflict'}:${id}`,episode:`test-${id}`,opened_message_id:id,last_message_id:id,opened_at:'2026-11-19T10:00:00',updated_at:'2026-11-19T10:00:00',type:severity===1?'separation':'conflict',severity,aircraft_ids:['B2','A1'],aircraft_id:'B2',reason:severity===1?'':'Low on gas',destination:severity===1?[40.81,-73.8]:null,status:severity===1?'instructed':'active',reports:1});
  state.active=[incident(1)]; state.opened_count=1;
  await page.goto('http://command.test/'); await page.waitForFunction(()=>lastAlertSnapshot!==null && !refreshing);
  await page.evaluate(()=>{window.toneCalls=0;const original=playAlertTone;playAlertTone=()=>{window.toneCalls++;return original();};});
  assert.equal(await page.locator('.flight-marker.alert-severity-1').count(),2);
  assert.equal(await page.locator('.aircraft-alert-detail').count(),2);
  assert.equal(await page.getByRole('button',{name:'Mute alert sounds',exact:true}).count(),1);
  assert.equal(await page.evaluate(()=>soundEnabled),true);
  await page.getByRole('button',{name:'Refresh now',exact:true}).click();
  await page.waitForFunction(()=>audioContext?.state==='running');
  assert.equal(await page.evaluate(()=>soundEnabled),true);
  await refresh(); assert.equal(await page.evaluate(()=>toneCalls),0);
  state.opened_count=10; await refresh(); assert.equal(await page.evaluate(()=>toneCalls),0);
  state.opened_count=11; await refresh(); assert.equal(await page.evaluate(()=>toneCalls),1);
  await refresh(); assert.equal(await page.evaluate(()=>toneCalls),1);
  await page.getByRole('button',{name:'Mute alert sounds',exact:true}).click();
  state.opened_count+=10; await refresh(); assert.equal(await page.evaluate(()=>toneCalls),1);
  await page.getByRole('button',{name:'Enable alert sounds',exact:true}).click();
  await refresh(); assert.equal(await page.evaluate(()=>toneCalls),1);
  assert.equal(await page.getByRole('button',{name:'Acknowledge',exact:true}).count(),0);
  assert.equal(await page.locator('.flight-marker.alert-severity-1').count(),2);
  await page.locator('#message-input').fill('Keep my draft');
  await page.getByRole('button',{name:'Contact Tower',exact:true}).click();
  assert.equal(await page.locator('#message-input').inputValue(),'Keep my draft');
  await page.reload(); await page.waitForFunction(()=>lastAlertSnapshot!==null && !refreshing);
  assert.equal(await page.evaluate(()=>newIncidentCount),0);
  assert.equal(await page.evaluate(()=>soundEnabled),true);
  state.active=[incident(2,2)]; state.recent=[{...incident(1),status:'resolved'}];state.opened_count=12;
