  failed=true; await refresh();
  assert.equal(await page.locator('#alerts-error').isVisible(),true);
  assert.equal(await page.locator('.flight-marker.alert-severity-2').count(),2);
  failed=false; state.active=[]; await refresh();
  assert.equal(await page.locator('.flight-marker.alert-severity-2').count(),0);
  assert.equal(await page.locator('.flight-marker.arrival').count(),2);
  state.sound_every=3; await refresh();
  await page.evaluate(()=>{window.toneCalls=0;playAlertTone=()=>{window.toneCalls++;return true;};soundEnabled=true;});
  state.opened_count+=2; await refresh();assert.equal(await page.evaluate(()=>toneCalls),0);
  state.opened_count++; await refresh();assert.equal(await page.evaluate(()=>toneCalls),1);
  state.active=[incident(3),incident(4,2)];await refresh();
  // Both incident severities on the same aircraft retain the highest warning.
  assert.equal(await page.locator('.flight-marker.alert-severity-1').count(),2);
  await page.getByRole('button',{name:'View B2',exact:true}).first().click();
  assert.equal(await page.evaluate(()=>selectedAircraft),'B2');
  await page.setViewportSize({width:390,height:844});await refresh();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
